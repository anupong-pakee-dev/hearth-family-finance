/**
 * Auto-escaping HTML templates. Every interpolated value is escaped unless it is already SafeHtml.
 */
export interface SafeHtml { readonly __html: string }

const ESC: Record<string, string> = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;', '`': '&#96;' };
export function esc(v: unknown): string {
  return String(v).replace(/[&<>"'`]/g, (c) => ESC[c]);
}

export function isSafe(v: unknown): v is SafeHtml {
  return typeof v === 'object' && v !== null && '__html' in v;
}

function render(v: unknown): string {
  if (v == null || v === false || v === true) return '';
  if (isSafe(v)) return v.__html;
  if (Array.isArray(v)) return v.map(render).join('');
  return esc(v);
}

export function html(strings: TemplateStringsArray, ...values: unknown[]): SafeHtml {
  let out = strings[0];
  for (let i = 0; i < values.length; i++) out += render(values[i]) + strings[i + 1];
  return { __html: out };
}

/** Trusted, already-safe markup (use only for markup generated by our own code). */
export function raw(s: string): SafeHtml { return { __html: s }; }

export function join(items: unknown[], sep: SafeHtml | string = ''): SafeHtml {
  return raw(items.map(render).join(isSafe(sep) ? sep.__html : esc(sep)));
}

export function attrs(a: Record<string, string | number | boolean | null | undefined>): SafeHtml {
  return raw(Object.entries(a).filter(([, v]) => v !== false && v != null).map(([k, v]) => (v === true ? ` ${k}` : ` ${k}="${esc(v)}"`)).join(''));
}
