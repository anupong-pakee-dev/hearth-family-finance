#!/usr/bin/env node
// First-time setup for docker compose (NFR-SEC-32): generates a random database password and master key.
// There are NO default passwords — compose refuses to start until this has run.
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const env = join(root, '.env');
const secrets = join(root, 'deploy', 'secrets');
mkdirSync(secrets, { recursive: true });

const write = (file, value) => {
  if (existsSync(file)) { console.log(`keep existing ${file}`); return; }
  writeFileSync(file, value, { mode: 0o600 });
  console.log(`created ${file}`);
};

write(join(secrets, 'db_password'), randomBytes(24).toString('base64url'));
write(join(secrets, 'master_keys'), `k${new Date().getFullYear()}a:${randomBytes(32).toString('base64')}`);
write(env, [
  '# Hearth Family Finance — generated by deploy/setup.mjs',
  'HEARTH_BASE_URL=https://finance.example.com',
  'HEARTH_TRUST_PROXY=true',
  'HEARTH_SESSION_IDLE_MINUTES=30',
  'HEARTH_BACKUP_INTERVAL_HOURS=24',
  '',
].join('\n'));
console.log('\nNext: edit .env (HEARTH_BASE_URL), back up deploy/secrets/master_keys OUTSIDE the server, then run: docker compose up -d');
